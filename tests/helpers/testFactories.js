/**
 * Factory for creating multiple test sessions for testing game listing functionality
 * @param {Object[]} sessionConfigs - Array of session configuration objects
 * @returns {{sessionManager: SessionManager, sessions: GameSession[]}} Session manager with multiple sessions
 */
export function createMultipleTestSessions(sessionConfigs = []) {
  const sessionManager = new SessionManager();
  const sessions = [];

  sessionConfigs.forEach((config) => {
    const { playerConfigs = [], sessionId = null } = config;
    const session = createGameSessionWithPlayers(playerConfigs);

    if (sessionId) {
      session.gameSessionID = sessionId;
    }

    sessionManager.addSession(session.gameSessionID, session);

    //set up player mappings
    playerConfigs.forEach((playerConfig) => {
      const player = createTestPlayer(
        playerConfig.username,
        playerConfig.socketId,
        playerConfig.colour
      );
      sessionManager.addPlayer(playerConfig.socketId, player);
      sessionManager.mapSocketToSession(
        playerConfig.socketId,
        session.gameSessionID
      );
    });

    sessions.push(session);
  });

  return { sessionManager, sessions };
}
